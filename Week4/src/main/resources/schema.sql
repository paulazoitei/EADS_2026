CREATE TABLE IF NOT EXISTS depots (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      name VARCHAR(150) NOT NULL,
    coordinates VARCHAR(255) NOT NULL,

    CONSTRAINT uk_depots_name UNIQUE (name)
    );

CREATE TABLE IF NOT EXISTS drivers (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(50),

    CONSTRAINT uk_drivers_email UNIQUE (email)
    );

CREATE TABLE IF NOT EXISTS vehicles (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        name VARCHAR(150) NOT NULL,
    capacity INTEGER NOT NULL,
    depot_id BIGINT NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    driver_id BIGINT UNIQUE,

    CONSTRAINT ck_vehicles_capacity_positive
    CHECK (capacity > 0),

    CONSTRAINT fk_vehicles_depot
    FOREIGN KEY (depot_id)
    REFERENCES depots(id),

    CONSTRAINT fk_vehicles_driver
    FOREIGN KEY (driver_id)
    REFERENCES drivers(id)
    );

CREATE TABLE IF NOT EXISTS customers (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(50),
    address VARCHAR(255) NOT NULL,
    coordinates VARCHAR(255) NOT NULL,

    CONSTRAINT uk_customers_email UNIQUE (email)
    );

CREATE TABLE IF NOT EXISTS deliveries (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          customer_id BIGINT NOT NULL,
                                          quantity INTEGER NOT NULL,
                                          notes VARCHAR(500),
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_deliveries_quantity_positive
    CHECK (quantity > 0),

    CONSTRAINT fk_deliveries_customer
    FOREIGN KEY (customer_id)
    REFERENCES customers(id)
    );